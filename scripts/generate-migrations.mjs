#!/usr/bin/env node
/**
 * Inlines `migrations/*.sql` into a plain TypeScript module.
 *
 * The Worker applies its own migrations, so the SQL has to reach the bundle.
 * `import.meta.glob` cannot do it: `src/worker.ts` is bundled by wrangler with
 * esbuild rather than by Vite, so the call survives untransformed and throws
 * `(intermediate value).glob is not a function` when Cloudflare validates the
 * upload. A generated module is understood by both.
 *
 * The output is committed, so `vite dev` and a fresh clone need no build step;
 * `migrations.generated.test.ts` fails if it drifts from the .sql files.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const dir = path.join(root, 'migrations');
const out = path.join(root, 'src/lib/server/migrations/migrations.generated.ts');

const files = readdirSync(dir)
	.filter((name) => name.endsWith('.sql'))
	.sort();

if (files.length === 0) {
	throw new Error('No migrations found to generate from.');
}

const entries = files
	.map((name) => {
		// Normalized regardless of the checkout's line endings (e.g. Windows + core.autocrlf) —
		// otherwise a CRLF working tree bakes CRLF into this file's string literals, which then
		// mismatches migrations.generated.test.ts on a Linux CI runner that checks out plain LF.
		const sql = readFileSync(path.join(dir, name), 'utf8').replace(/\r\n/g, '\n');
		return `\t{\n\t\tname: ${JSON.stringify(name)},\n\t\tsql: ${JSON.stringify(sql)}\n\t}`;
	})
	.join(',\n');

const contents = `// Generated by scripts/generate-migrations.mjs — do not edit.
// Run \`bun scripts/generate-migrations.mjs\` after adding a migration.

export type GeneratedMigration = { name: string; sql: string };

/** Every file in \`migrations/\`, in the order wrangler would apply them. */
export const MIGRATIONS: GeneratedMigration[] = [
${entries}
];
`;

writeFileSync(out, contents, 'utf8');
console.log(`generate-migrations: ${files.length} migrations -> ${path.relative(root, out)}`);
